import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

interface RevisionPin {
  revision: string;
}

interface NoticePins {
  shellParser: RevisionPin & { directory: string };
  oils: RevisionPin;
  brush: RevisionPin;
}

interface CargoPackage {
  name: string;
  version: string;
  manifest_path: string;
}

interface CargoMetadata {
  packages: CargoPackage[];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function validateRevisionPin(pin: unknown): asserts pin is RevisionPin {
  assert.ok(isRecord(pin));
  assert.ok(typeof pin.revision === "string");
}

function validateNoticePins(pins: unknown): asserts pins is NoticePins {
  assert.ok(isRecord(pins));
  validateRevisionPin(pins.shellParser);
  assert.ok(isRecord(pins.shellParser));
  assert.ok(typeof pins.shellParser.directory === "string");
  validateRevisionPin(pins.oils);
  validateRevisionPin(pins.brush);
}

function validateCargoMetadata(metadata: unknown): asserts metadata is CargoMetadata {
  assert.ok(isRecord(metadata));
  assert.ok(Array.isArray(metadata.packages));
  for (const pkg of metadata.packages) {
    assert.ok(isRecord(pkg));
    assert.ok(typeof pkg.name === "string");
    assert.ok(typeof pkg.version === "string");
    assert.ok(typeof pkg.manifest_path === "string");
  }
}

const root = resolve(import.meta.dirname, "..");
const pins: unknown = JSON.parse(await readFile(resolve(root, "sources.lock.json"), "utf8"));
validateNoticePins(pins);
let output = "# Third-party notices\n\nThis file is generated by `npm run notices:shell`.\n\n";

async function include(label: string, directory: string) {
  const names = (await readdir(directory).catch(() => []))
    .filter((name) => /^(license|copying|notice)(\.|-|$)/i.test(name))
    .sort();
  for (const name of names) {
    const text = await readFile(resolve(directory, name), "utf8").catch(() => undefined);
    if (text) {
      const normalized = text.replaceAll("\r\n", "\n").replace(/[ \t]+$/gm, "");
      output += `## ${label} / ${name}\n\n${normalized}\n\n`;
    }
  }
}

const metadata: unknown = JSON.parse(
  execFileSync(
    "cargo",
    ["metadata", "--locked", "--format-version", "1", "--manifest-path", "shell/Cargo.toml"],
    { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
  ),
);
validateCargoMetadata(metadata);
const included = new Set<string>();
for (const pkg of metadata.packages.sort((a, b) => a.name.localeCompare(b.name))) {
  if (included.has(pkg.manifest_path) || pkg.name === "shell-parser") continue;
  included.add(pkg.manifest_path);
  await include(`${pkg.name} ${pkg.version}`, dirname(pkg.manifest_path));
}
// Python is optional and separately packaged. Include its complete producer notices
// only when the optional assets are present in this composition.
if ((await readdir(resolve(root, "dist"))).includes("python.wasm")) {
  const pythonNotices = await readFile(resolve(root, "dist/python.NOTICES.txt"), "utf8");
  output += `## CPython 3.15.2 and full standard-library payload\n\n${pythonNotices}\n\n`;
}
const parserLicense = await readFile(resolve(root, pins.shellParser.directory, "LICENSE"), "utf8");
output += `## Bashkit parser ${pins.shellParser.revision} / LICENSE\n\n${parserLicense}\n\n`;
await include(`Oils corpus ${pins.oils.revision}`, resolve(root, "docs/evidence/licenses"));
await include(`Brush corpus ${pins.brush.revision}`, resolve(root, "docs/evidence/licenses"));
const oilsLicense = await readFile(
  resolve(root, "docs/evidence/licenses/oils-LICENSE.txt"),
  "utf8",
);
const brushLicense = await readFile(resolve(root, "docs/evidence/licenses/brush-MIT.txt"), "utf8");
output += `## Pinned Oils corpus ${pins.oils.revision}\n\n${oilsLicense}\n\n`;
output += `## Pinned Brush corpus ${pins.brush.revision}\n\n${brushLicense}\n`;
await mkdir(resolve(root, "dist"), { recursive: true });
await writeFile(resolve(root, "dist/THIRD_PARTY_NOTICES.txt"), output);
