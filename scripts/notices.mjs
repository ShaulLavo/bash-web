import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

const root = resolve(import.meta.dirname, "..");
const pins = JSON.parse(await readFile(resolve(root, "sources.lock.json"), "utf8"));
let output = "# Third-party notices\n\nThis file is generated by `npm run notices:shell`.\n\n";

async function include(label, directory) {
  const names = (await readdir(directory).catch(() => []))
    .filter((name) => /^(license|copying|notice)(\.|-|$)/i.test(name))
    .sort();
  for (const name of names) {
    const text = await readFile(resolve(directory, name), "utf8").catch(() => undefined);
    if (text) output += `## ${label} / ${name}\n\n${text}\n\n`;
  }
}

const metadata = JSON.parse(
  execFileSync(
    "cargo",
    ["metadata", "--locked", "--format-version", "1", "--manifest-path", "shell/Cargo.toml"],
    { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
  ),
);
const included = new Set();
for (const pkg of metadata.packages.sort((a, b) => a.name.localeCompare(b.name))) {
  if (included.has(pkg.manifest_path) || pkg.name === "shell-parser") continue;
  included.add(pkg.manifest_path);
  await include(`${pkg.name} ${pkg.version}`, dirname(pkg.manifest_path));
}
const parserLicense = await readFile(resolve(root, pins.shellParser.directory, "LICENSE"), "utf8");
output += `## Bashkit parser ${pins.shellParser.revision} / LICENSE\n\n${parserLicense}\n\n`;
await include(`Oils corpus ${pins.oils.revision}`, resolve(root, "docs/evidence/licenses"));
await include(`Brush corpus ${pins.brush.revision}`, resolve(root, "docs/evidence/licenses"));
const oilsLicense = await readFile(
  resolve(root, "docs/evidence/licenses/oils-LICENSE.txt"),
  "utf8",
);
const brushLicense = await readFile(resolve(root, "docs/evidence/licenses/brush-MIT.txt"), "utf8");
output += `## Pinned Oils corpus ${pins.oils.revision}\n\n${oilsLicense}\n\n`;
output += `## Pinned Brush corpus ${pins.brush.revision}\n\n${brushLicense}\n`;
await mkdir(resolve(root, "dist"), { recursive: true });
await writeFile(resolve(root, "dist/THIRD_PARTY_NOTICES.txt"), output);
