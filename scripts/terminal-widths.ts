// Generates the line editor's cell-width table from the pinned libghostty-vt, so the
// editor counts cells exactly as the terminal places them with mode 2027 off (its default).
// `node scripts/terminal-widths.ts` rewrites the table; `--check` fails when it is stale.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { ghosttyRevision, ghosttyRuntime } from "./ghostty-vt.ts";

const table = resolve(import.meta.dirname, "../shell/engine/src/terminal_width.rs");

function measured(width: (code: number) => number | undefined) {
  const runs = new Map<number, [number, number][]>([
    [0, []],
    [2, []],
  ]);
  let previous: [number, number] | undefined;
  for (let code = 0x100; code < 0x110000; code++) {
    const cells = width(code);
    // Surrogates never reach the terminal, so they may join either neighbor's run.
    if (cells === undefined) continue;
    const list = runs.get(cells);
    if (list === undefined) {
      previous = undefined;
      continue;
    }
    if (previous && list.at(-1) === previous) {
      previous[1] = code;
      continue;
    }
    previous = [code, code];
    list.push(previous);
  }
  return runs;
}

function rust(name: string, ranges: readonly [number, number][]) {
  const hex = (code: number) => `0x${code.toString(16)}`;
  const rows = [];
  for (let at = 0; at < ranges.length; at += 6) {
    const row = ranges.slice(at, at + 6).map(([start, end]) => `(${hex(start)}, ${hex(end)}),`);
    rows.push(`    ${row.join(" ")}`);
  }
  return `#[rustfmt::skip]\npub(super) const ${name}: &[(u32, u32)] = &[\n${rows.join("\n")}\n];\n`;
}

export async function generatedWidthTable() {
  const runtime = await ghosttyRuntime();
  const terminal = runtime.createTerminal({ columns: 8, rows: 2 });
  const runs = measured((code) => {
    if (code >= 0xd800 && code <= 0xdfff) return undefined;
    terminal.write(`\x1b[H\x1b[2Ka${String.fromCodePoint(code)}`);
    return terminal.cursor.x - 1;
  });
  terminal.dispose();
  runtime.dispose();
  return [
    `// Generated by \`node scripts/terminal-widths.ts\` from libghostty-vt ${await ghosttyRevision()}.`,
    "// Cell widths above U+00FF with grapheme clustering off. Every other scalar is one cell.",
    "",
    rust("ZERO", runs.get(0)!),
    rust("WIDE", runs.get(2)!),
  ].join("\n");
}

if (import.meta.main) {
  const generated = await generatedWidthTable();
  if (process.argv.includes("--check")) {
    if ((await readFile(table, "utf8")) !== generated)
      throw new Error("terminal_width.rs is stale; run node scripts/terminal-widths.ts");
  } else {
    await writeFile(table, generated);
  }
}
